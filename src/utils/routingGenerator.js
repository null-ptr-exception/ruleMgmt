/**
 * Notification routing — from a deployment's routing.yaml to an
 * AlertmanagerConfig (#92, part of #56).
 *
 * routing.yaml is a table: `labels` are its dimensions and their values,
 * each entry of `cells` is one filled cell — a full label combination and
 * who to notify. A combination with no cell is an empty cell.
 *
 *   labels:   { severity: [critical, warning], team: [db, web] }
 *   defaults: { groupWait: 30s, repeatInterval: 4h }
 *   configs:  { db-email: { type: email, to: db@example.com } }
 *   cells:
 *     - match: { severity: critical, team: db }
 *       configs: [db-email]
 *       repeatInterval: 1h
 *
 * The resource is built so that the mistakes of a hand-written route tree
 * cannot be made:
 *
 *   - a cell is one route, one level below the root (the operator rewrites
 *     the root route), matching every label of the table, so no cell can
 *     shadow another and none needs `continue`
 *   - a cell with several configs gets one child route per config, all but
 *     the last with `continue: true`, so each of them is notified
 *   - everything no cell matches falls to the root's receiver `_drop`, which
 *     notifies nobody — an empty cell is a decision, not a gap
 *   - the resource's own root route says `continue: true`. The operator puts
 *     it under Alertmanager's root, ahead of every other AlertmanagerConfig
 *     and of the platform's routes, and prometheus-operator forces `continue`
 *     there anyway; VictoriaMetrics' operator does too unless
 *     `disableRouteContinueEnforce` is set, and then an unwritten `continue`
 *     would stop every alert here
 *   - a webhook address that carries a credential is refused; it belongs in
 *     a Secret (`urlSecret`)
 *
 * The output is a complete resource, written into the deployment's
 * templates/ so the deployment chart deploys it. Helm still reads the file as
 * a template, so `{{` and `}}` in any value are escaped; only the object name
 * is a template, following the release like the rule objects do.
 */

import yaml from 'js-yaml'
import { ROUTING } from './outputs.js'

export const DROP_RECEIVER = '_drop'

export const GENERATED_HEADER = '# Generated by AlertForge from routing.yaml. Edits here are overwritten.\n'

const TIMING_KEYS = ['groupWait', 'groupInterval', 'repeatInterval']
const TOP_KEYS = ['labels', 'defaults', 'configs', 'cells']
const CELL_KEYS = ['match', 'configs', ...TIMING_KEYS]
const CONFIG_FIELDS = {
  email: { required: ['to'], optional: [] },
  webhook: { required: [], optional: ['url', 'urlSecret'] },
}

const LABEL_NAME_RE = /^[a-zA-Z_][a-zA-Z0-9_]*$/
const CONFIG_NAME_RE = /^[a-z0-9][a-z0-9-]*$/
const DURATION_RE = /^([0-9]+(ms|s|m|h|d|w|y))+$/

const isMap = v => v !== null && typeof v === 'object' && !Array.isArray(v)
const isText = v => typeof v === 'string' && v.trim() !== ''

// Query parameter names that carry a credential, alone or as a suffix
// (`access_token`, `api-key`).
const SECRET_PARAM_RE = /(^|[_-])(token|key|apikey|secret|password|passwd|pwd|auth|sig|signature)$/i

/**
 * Whether a string looks like a generated credential: long, and mixing
 * letters with digits. Words, numbers and DNS names do not.
 */
export function looksLikeToken(text) {
  return typeof text === 'string' && text.length >= 20 && /[a-zA-Z]/.test(text) && /[0-9]/.test(text) && !text.includes('.')
}

/**
 * Why a webhook address must not be written in plain text, or null. The host
 * is never checked — an in-cluster service name is an address, not a secret.
 */
export function urlCredential(url) {
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    return null
  }
  if (parsed.username || parsed.password) return 'it carries a user name or password'
  for (const [name, value] of parsed.searchParams) {
    if (SECRET_PARAM_RE.test(name)) return `its query parameter "${name}" looks like a credential`
    if (looksLikeToken(value)) return `its query parameter "${name}" looks like a token`
  }
  const segment = parsed.pathname.split('/').find(looksLikeToken)
  if (segment) return 'its path contains what looks like a token'
  return null
}

function checkTiming(where, entry, errors) {
  for (const key of TIMING_KEYS) {
    if (entry[key] === undefined) continue
    if (typeof entry[key] !== 'string' || !DURATION_RE.test(entry[key])) {
      errors.push(`${where}: ${key} must be a duration such as 30s, 5m or 4h`)
    }
  }
}

function unknownKeys(where, entry, known, errors) {
  for (const key of Object.keys(entry)) {
    if (!known.includes(key)) errors.push(`${where}: unknown key "${key}" (expected ${known.join(', ')})`)
  }
}

function checkConfig(name, config, errors) {
  const where = `configs.${name}`
  if (name.startsWith('_')) {
    errors.push(`${where}: names starting with "_" are reserved (${DROP_RECEIVER} notifies nobody)`)
    return
  }
  if (!CONFIG_NAME_RE.test(name)) {
    errors.push(`${where}: a name is lower-case letters, digits and "-"`)
    return
  }
  if (!isMap(config)) {
    errors.push(`${where}: must be a map with a "type"`)
    return
  }
  const fields = CONFIG_FIELDS[config.type]
  if (!fields) {
    errors.push(`${where}: type must be one of ${Object.keys(CONFIG_FIELDS).join(', ')}`)
    return
  }
  unknownKeys(where, config, ['type', ...fields.required, ...fields.optional], errors)
  for (const key of fields.required) {
    if (!isText(config[key])) errors.push(`${where}: ${key} is required`)
  }
  if (config.type === 'webhook') {
    const hasUrl = config.url !== undefined
    const hasSecret = config.urlSecret !== undefined
    if (hasUrl === hasSecret) {
      errors.push(`${where}: a webhook has either url or urlSecret`)
    } else if (hasUrl) {
      if (!isText(config.url)) {
        errors.push(`${where}: url must be text`)
      } else {
        const why = urlCredential(config.url)
        if (why) errors.push(`${where}: url is refused because ${why}; put it in a Secret and use urlSecret`)
      }
    } else if (!isMap(config.urlSecret) || !isText(config.urlSecret.name) || !isText(config.urlSecret.key)) {
      errors.push(`${where}: urlSecret needs a Secret's name and key`)
    }
  }
}

/**
 * Every problem with a parsed routing.yaml, as messages naming where it is.
 * An empty list means it can be generated.
 */
export function checkRouting(routing) {
  const errors = []
  if (!isMap(routing)) return ['routing.yaml must be a map with labels, configs and cells']
  unknownKeys('routing.yaml', routing, TOP_KEYS, errors)

  const labels = isMap(routing.labels) ? routing.labels : null
  if (!labels || Object.keys(labels).length === 0) {
    errors.push('labels: name at least one label, with its values')
  } else {
    for (const [name, values] of Object.entries(labels)) {
      if (!LABEL_NAME_RE.test(name)) errors.push(`labels.${name}: not a valid label name`)
      if (!Array.isArray(values) || values.length === 0) {
        errors.push(`labels.${name}: list its values`)
      } else if (!values.every(isText)) {
        errors.push(`labels.${name}: values must be text — quote one that YAML reads otherwise (e.g. "true", "1")`)
      } else if (new Set(values).size !== values.length) {
        errors.push(`labels.${name}: a value is listed twice`)
      }
    }
  }

  if (routing.defaults !== undefined) {
    if (!isMap(routing.defaults)) {
      errors.push('defaults: must be a map')
    } else {
      unknownKeys('defaults', routing.defaults, TIMING_KEYS, errors)
      checkTiming('defaults', routing.defaults, errors)
    }
  }

  const configs = isMap(routing.configs) ? routing.configs : {}
  if (routing.configs !== undefined && !isMap(routing.configs)) errors.push('configs: must be a map of name → config')
  for (const [name, config] of Object.entries(configs)) checkConfig(name, config, errors)

  if (routing.cells !== undefined && !Array.isArray(routing.cells)) {
    errors.push('cells: must be a list')
    return errors
  }
  const seen = new Map()
  ;(routing.cells || []).forEach((cell, i) => {
    const where = `cells[${i}]`
    if (!isMap(cell)) {
      errors.push(`${where}: must be a map with match and configs`)
      return
    }
    unknownKeys(where, cell, CELL_KEYS, errors)
    checkTiming(where, cell, errors)

    if (!isMap(cell.match)) {
      errors.push(`${where}: match is required`)
    } else if (labels) {
      // A cell that leaves a label out would match every value of it and
      // cover its neighbours' combinations.
      for (const name of Object.keys(labels)) {
        if (cell.match[name] === undefined) errors.push(`${where}: match has no ${name} — a cell names every label`)
      }
      for (const [name, value] of Object.entries(cell.match)) {
        if (!Object.hasOwn(labels, name)) {
          errors.push(`${where}: match names ${name}, which is not in labels`)
        } else if (Array.isArray(labels[name]) && !labels[name].includes(value)) {
          errors.push(`${where}: ${name}=${value} is not one of labels.${name}`)
        }
      }
      const key = JSON.stringify(Object.keys(labels).map(name => cell.match[name]))
      if (seen.has(key)) errors.push(`${where}: same match as cells[${seen.get(key)}]`)
      else seen.set(key, i)
    }

    if (!Array.isArray(cell.configs) || cell.configs.length === 0) {
      errors.push(`${where}: configs lists who is notified`)
    } else {
      for (const name of cell.configs) {
        if (!Object.hasOwn(configs, name)) errors.push(`${where}: config "${name}" is not in configs`)
      }
      if (new Set(cell.configs).size !== cell.configs.length) errors.push(`${where}: a config is listed twice`)
    }
  })
  return errors
}

function receiverFor(name, config) {
  if (config.type === 'email') return { name, emailConfigs: [{ to: config.to }] }
  const webhook = config.urlSecret
    ? { urlSecret: { name: config.urlSecret.name, key: config.urlSecret.key } }
    : { url: config.url }
  return { name, webhookConfigs: [webhook] }
}

function timing(defaults, cell) {
  const out = {}
  for (const key of TIMING_KEYS) {
    const value = cell[key] ?? defaults?.[key]
    if (value !== undefined) out[key] = value
  }
  return out
}

/** The resource's spec, as data: the root drops, one route per cell. */
export function routingSpec(routing) {
  const labelNames = Object.keys(routing.labels)
  const used = new Set((routing.cells || []).flatMap(cell => cell.configs))
  const routes = (routing.cells || []).map(cell => {
    const route = {
      matchers: labelNames.map(name => ({ name, value: cell.match[name], matchType: '=' })),
      ...timing(routing.defaults, cell),
    }
    if (cell.configs.length === 1) return { ...route, receiver: cell.configs[0] }
    route.routes = cell.configs.map((name, i) => (
      i < cell.configs.length - 1 ? { receiver: name, continue: true } : { receiver: name }
    ))
    return route
  })
  return {
    route: { receiver: DROP_RECEIVER, continue: true, ...(routes.length ? { routes } : {}) },
    receivers: [
      { name: DROP_RECEIVER },
      // In the order configs are declared; one no cell uses is left out.
      ...Object.entries(routing.configs || {})
        .filter(([name]) => used.has(name))
        .map(([name, config]) => receiverFor(name, config)),
    ],
  }
}

// `{{` and `}}` reach the cluster as written: Helm turns `{{ "{{" }}` back
// into `{{`. One pass, so a replacement is never replaced again.
export const escapeBraces = text => text.replace(/\{\{|\}\}/g, m => `{{ "${m}" }}`)

/**
 * The file for templates/: the AlertmanagerConfig for a parsed routing.yaml.
 * `meta` is the object's labels and annotations (objectMeta.js), already
 * resolved for this kind of object. Returns `{ text }`, or `{ errors }` when
 * the routing does not pass checkRouting.
 */
export function generateRouting(routing, { meta = {} } = {}) {
  const errors = checkRouting(routing)
  if (errors.length) return { errors }
  const name = '__ALERTFORGE_NAME__'
  const doc = {
    // prometheus-operator's AlertmanagerConfig — config/outputs.json.
    ...ROUTING,
    metadata: {
      name,
      ...(Object.keys(meta.labels || {}).length ? { labels: meta.labels } : {}),
      ...(Object.keys(meta.annotations || {}).length ? { annotations: meta.annotations } : {}),
    },
    spec: routingSpec(routing),
  }
  const body = escapeBraces(yaml.dump(doc, { lineWidth: -1, noRefs: true }))
  return { text: GENERATED_HEADER + body.replace(name, () => '{{ .Release.Name }}-routing') }
}
