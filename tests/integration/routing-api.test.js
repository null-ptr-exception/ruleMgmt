import { describe, it, expect, beforeAll, afterAll, beforeEach, afterEach } from 'vitest'
import express from 'express'
import request from 'supertest'
import fs from 'fs'
import path from 'path'
import os from 'os'
import yaml from 'js-yaml'
import deploymentsRouter from '../../server/routes/deployments.js'
import syncRouter from '../../server/routes/sync.js'
import renderRouter from '../../server/routes/render.js'
import foldersRouter from '../../server/routes/folders.js'
import { writeSyncRegistry } from '../../server/lib/sync.js'

/**
 * A deployment's notification routing (#92): routing.yaml and the
 * AlertmanagerConfig generated from it, through the deployments, sync, render
 * and folders routes. What the generator produces is pinned in
 * routingGenerator.test.js and the routing blind cases.
 */

const CHART_WITH_DEP = yaml.dump({
  apiVersion: 'v2',
  name: 'prod',
  version: '1.0.0',
  dependencies: [{ name: 'mariadb-alerts', version: '2.0.0', repository: 'file://../../charts/mariadb-alerts' }],
})

const ROUTING = fs.readFileSync(path.resolve('tests/fixtures/routing/basic/routing.yaml'), 'utf-8')
const CR = path.join('templates', 'alertmanagerconfig.yaml')

let tmpDir, app, savedEnv

beforeAll(() => {
  savedEnv = { HELM_BIN: process.env.HELM_BIN, RULE_OBJECT_LABELS: process.env.RULE_OBJECT_LABELS }
  // Preview's helm: nothing to render, which leaves the routing check alone
  // to look at.
  const bin = fs.mkdtempSync(path.join(os.tmpdir(), 'routing-api-helm-'))
  process.env.HELM_BIN = path.join(bin, 'helm')
  fs.writeFileSync(process.env.HELM_BIN, '#!/bin/sh\nexit 0\n', { mode: 0o755 })
})

afterAll(() => {
  fs.rmSync(path.dirname(process.env.HELM_BIN), { recursive: true, force: true })
  for (const [k, v] of Object.entries(savedEnv)) {
    if (v === undefined) delete process.env[k]
    else process.env[k] = v
  }
})

beforeEach(() => {
  delete process.env.RULE_OBJECT_LABELS
  tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'routing-api-test-'))
  app = express()
  app.use(express.json())
  app.use((req, res, next) => { req.gitopsDir = tmpDir; next() })
  app.use('/api/v2/deployments', deploymentsRouter())
  app.use('/api/v2/sync', syncRouter())
  app.use('/api/v2/render', renderRouter())
  app.use('/api/v2/folders', foldersRouter())
})

afterEach(() => {
  fs.rmSync(tmpDir, { recursive: true, force: true })
})

function makeDeployment(relPath) {
  const dir = path.join(tmpDir, relPath)
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'Chart.yaml'), CHART_WITH_DEP)
  fs.writeFileSync(path.join(dir, 'values.yaml'), 'mariadb-alerts: {}\n')
  return dir
}

const routingUrl = folder => `/api/v2/deployments/mariadb-alerts/${path.basename(folder)}/routing?folder=${encodeURIComponent(folder)}`
const putRouting = (folder, routing) => request(app).put(routingUrl(folder)).send({ routing })
const render = folder => request(app).post(`/api/v2/render/mariadb-alerts/${path.basename(folder)}?folder=${encodeURIComponent(folder)}`).send({})
const read = (dir, file) => fs.readFileSync(path.join(dir, file), 'utf-8')
const has = (dir, file) => fs.existsSync(path.join(dir, file))

describe('PUT routing', () => {
  it('writes routing.yaml as sent, and the AlertmanagerConfig from it', async () => {
    const dir = makeDeployment('asia/prod')
    const text = `# kept as written\n${ROUTING}`
    const res = await putRouting('asia/prod', text)
    expect(res.status).toBe(200)
    expect(read(dir, 'routing.yaml')).toBe(text)
    const cr = read(dir, CR)
    expect(cr).toMatch(/^# Generated by AlertForge from routing.yaml/)
    expect(cr).toContain('kind: AlertmanagerConfig')
    expect(cr).toContain('app.kubernetes.io/managed-by: Helm')
  })

  it('takes the table too, written out as YAML', async () => {
    const dir = makeDeployment('asia/prod')
    const res = await putRouting('asia/prod', yaml.load(ROUTING))
    expect(res.status).toBe(200)
    expect(yaml.load(read(dir, 'routing.yaml'))).toEqual(yaml.load(ROUTING))
    expect(has(dir, CR)).toBe(true)
  })

  it('puts the routing kind\'s labels on the object', async () => {
    process.env.RULE_OBJECT_LABELS = '{"release":"kps"}'
    process.env.RULE_OBJECT_LABELS_BY_PROFILE = '{"routing":{"release":"kps-alertmanager"}}'
    try {
      const dir = makeDeployment('asia/prod')
      await putRouting('asia/prod', ROUTING)
      // The file is a Helm template only in its name.
      const doc = yaml.load(read(dir, CR).replace('{{ .Release.Name }}', 'rel'))
      expect(doc.metadata.labels).toEqual({ 'app.kubernetes.io/managed-by': 'Helm', release: 'kps-alertmanager' })
    } finally {
      delete process.env.RULE_OBJECT_LABELS_BY_PROFILE
    }
  })

  it('refuses a routing.yaml with problems and writes neither file', async () => {
    const dir = makeDeployment('asia/prod')
    const unknown = ROUTING.replace('configs: [db-email]', 'configs: [nobody]')
    const token = ROUTING.replace('http://alert-relay.monitoring.svc:8080', 'https://hooks.example.com/x?token=abc123')
    for (const bad of [unknown, token, 'labels: [', 'just text']) {
      const res = await putRouting('asia/prod', bad)
      expect(res.status).toBe(400)
      expect(res.body.problems.length).toBeGreaterThan(0)
    }
    expect(has(dir, 'routing.yaml')).toBe(false)
    expect(has(dir, CR)).toBe(false)
  })

  it('refuses a request with no routing', async () => {
    makeDeployment('asia/prod')
    expect((await request(app).put(routingUrl('asia/prod')).send({})).status).toBe(400)
  })

  it('is for a folder deployment only', async () => {
    fs.mkdirSync(path.join(tmpDir, 'deployments', 'mariadb-alerts'), { recursive: true })
    fs.writeFileSync(path.join(tmpDir, 'deployments', 'mariadb-alerts', 'prod-values.yaml'), '')
    const flat = await request(app).put('/api/v2/deployments/mariadb-alerts/prod/routing').send({ routing: ROUTING })
    expect(flat.status).toBe(400)
    // A legacy sibling inside a folder is not the folder's deployment either.
    makeDeployment('asia/prod')
    const sibling = await request(app).put('/api/v2/deployments/mariadb-alerts/other/routing?folder=asia%2Fprod').send({ routing: ROUTING })
    expect(sibling.status).toBe(400)
  })
})

describe('DELETE routing', () => {
  it('removes both files and the templates/ made for them', async () => {
    const dir = makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    const res = await request(app).delete(routingUrl('asia/prod'))
    expect(res.status).toBe(200)
    expect(has(dir, 'routing.yaml')).toBe(false)
    expect(has(dir, 'templates')).toBe(false)
    expect(has(dir, 'values.yaml')).toBe(true)
  })

  it('leaves other templates alone', async () => {
    const dir = makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    fs.writeFileSync(path.join(dir, 'templates', 'extra.yaml'), 'x: 1\n')
    await request(app).delete(routingUrl('asia/prod'))
    expect(has(dir, CR)).toBe(false)
    expect(has(dir, path.join('templates', 'extra.yaml'))).toBe(true)
  })
})

describe('sync', () => {
  it('copies the source\'s routing to its targets on PUT and DELETE', async () => {
    makeDeployment('asia/prod')
    const target = makeDeployment('eu/prod')
    await writeSyncRegistry(tmpDir, { syncs: [{ source: 'asia/prod', targets: ['eu/prod'] }] })

    await putRouting('asia/prod', ROUTING)
    expect(read(target, 'routing.yaml')).toBe(ROUTING)
    expect(read(target, CR)).toBe(read(path.join(tmpDir, 'asia/prod'), CR))

    await request(app).delete(routingUrl('asia/prod'))
    expect(has(target, 'routing.yaml')).toBe(false)
    expect(has(target, CR)).toBe(false)
  })

  it('refuses to change a target\'s routing', async () => {
    makeDeployment('asia/prod')
    const target = makeDeployment('eu/prod')
    await writeSyncRegistry(tmpDir, { syncs: [{ source: 'asia/prod', targets: ['eu/prod'] }] })
    expect((await putRouting('eu/prod', ROUTING)).status).toBe(409)
    expect((await request(app).delete(routingUrl('eu/prod'))).status).toBe(409)
    expect(has(target, 'routing.yaml')).toBe(false)
  })

  it('copies routing when a sync is created, and removes a target\'s own when the source has none', async () => {
    const source = makeDeployment('asia/prod')
    const withRouting = makeDeployment('eu/prod')
    const own = makeDeployment('us/prod')
    await putRouting('asia/prod', ROUTING)
    await putRouting('us/prod', ROUTING.replace('repeatInterval: 1h', 'repeatInterval: 2h'))

    expect((await request(app).post('/api/v2/sync').send({ source: 'asia/prod', target: 'eu/prod' })).status).toBe(200)
    expect(read(withRouting, 'routing.yaml')).toBe(read(source, 'routing.yaml'))
    expect(read(withRouting, CR)).toBe(read(source, CR))

    makeDeployment('jp/prod')
    expect((await request(app).post('/api/v2/sync').send({ source: 'jp/prod', target: 'us/prod' })).status).toBe(200)
    expect(has(own, 'routing.yaml')).toBe(false)
    expect(has(own, CR)).toBe(false)
  })
})

describe('GET routing', () => {
  const getRouting = folder => request(app).get(routingUrl(folder))

  it('is 404 for a deployment with no routing.yaml', async () => {
    makeDeployment('asia/prod')
    expect((await getRouting('asia/prod')).status).toBe(404)
  })

  it('returns routing.yaml as written, and passes one saved through the API', async () => {
    makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    const res = await getRouting('asia/prod')
    expect(res.status).toBe(200)
    expect(res.body).toEqual({ text: ROUTING, errors: [], stale: false })
  })

  it('reports the AlertmanagerConfig out of date after routing.yaml is edited by hand, until it is saved again', async () => {
    const dir = makeDeployment('asia/prod')
    // Hand-written, never generated: no AlertmanagerConfig at all.
    fs.writeFileSync(path.join(dir, 'routing.yaml'), ROUTING)
    let state = (await getRouting('asia/prod')).body
    expect(state).toMatchObject({ errors: [], stale: true })

    // Saving the text as it is regenerates it.
    expect((await putRouting('asia/prod', state.text)).status).toBe(200)
    expect((await getRouting('asia/prod')).body.stale).toBe(false)

    fs.writeFileSync(path.join(dir, 'routing.yaml'), ROUTING.replace('repeatInterval: 1h', 'repeatInterval: 2h'))
    state = (await getRouting('asia/prod')).body
    expect(state.stale).toBe(true)
  })

  it('reports the AlertmanagerConfig out of date when the site\'s labels change', async () => {
    makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    process.env.RULE_OBJECT_LABELS = '{"release":"kps"}'
    expect((await getRouting('asia/prod')).body.stale).toBe(true)
  })

  it('reports a routing.yaml\'s problems with the same check as saving it', async () => {
    const dir = makeDeployment('asia/prod')
    fs.writeFileSync(path.join(dir, 'routing.yaml'), ROUTING.replace('configs: [db-email]', 'configs: [nobody]'))
    expect((await getRouting('asia/prod')).body.errors).toEqual(['cells[1]: config "nobody" is not in configs'])
  })

  it('reads a synced target\'s routing', async () => {
    makeDeployment('asia/prod')
    makeDeployment('eu/prod')
    await writeSyncRegistry(tmpDir, { syncs: [{ source: 'asia/prod', targets: ['eu/prod'] }] })
    await putRouting('asia/prod', ROUTING)
    expect((await getRouting('eu/prod')).body).toEqual({ text: ROUTING, errors: [], stale: false })
  })
})

describe('Preview', () => {
  it('reports nothing about routing: its check is GET routing\'s', async () => {
    makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    const res = await render('asia/prod')
    expect(res.body.ok).toBe(true)
    expect(res.body).not.toHaveProperty('routingCheck')
  })
})

describe('the folder tree', () => {
  it('keeps a deployment with templates/ and charts/ a leaf', async () => {
    const dir = makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    fs.mkdirSync(path.join(dir, 'charts'))
    const res = await request(app).get('/api/v2/folders/tree?path=asia')
    expect(res.body).toHaveLength(1)
    expect(res.body[0]).toMatchObject({ name: 'prod', isDeployment: true, isLeaf: true })
  })

  it('lists a deployment\'s real subfolders, but not its templates/', async () => {
    const dir = makeDeployment('asia/prod')
    await putRouting('asia/prod', ROUTING)
    fs.mkdirSync(path.join(dir, 'canary'))
    const parent = await request(app).get('/api/v2/folders/tree?path=asia')
    expect(parent.body[0].isLeaf).toBe(false)
    const children = await request(app).get('/api/v2/folders/tree?path=asia/prod')
    expect(children.body.map(n => n.name)).toEqual(['canary'])
  })

  it('still shows a folder named templates outside a deployment', async () => {
    fs.mkdirSync(path.join(tmpDir, 'templates'))
    const res = await request(app).get('/api/v2/folders/tree')
    expect(res.body.map(n => n.name)).toContain('templates')
  })
})
